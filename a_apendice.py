# -*- coding: utf-8 -*-
"""
Converts supplementary_v2.tex (built by suplementario.py) into apendices.tex,
a set of appendices for the main manuscript (Elsevier cas-dc class):

  Appendix A  Mathematical results
  Appendix B  Synthetic validation and diagnostic of the submitted analysis
  Appendix C  Community model: medium and curation
  Appendix D  Additional results
  Appendix E  Cross-feeding in the community model
  Appendix F  Software and reproducibility

Numbering follows Elsevier's rule for appendices (Table A.1, Fig. B.1,
Eq. (A.1), Proposition A.1). Cross-references to the supplement become
\\ref{} to the main text's own labels. Usage, after suplementario.py:

    python a_apendice.py            # writes apendices.tex
    # in the main .tex, after the Acknowledgements:  \\input{apendices}
"""
import re

SRC = "supplementary_v2.tex"   # written by suplementario_v2.py
DST = "apendices.tex"

RESET = (r"\setcounter{figure}{0}\setcounter{table}{0}\setcounter{equation}{0}"
         r"\setcounter{proposition}{0}\setcounter{lemma}{0}\setcounter{remark}{0}")

CABECERA = r"""%% ======================================================================
%% Appendices -- generated by a_apendice.py from supplementary_v2.tex.
%% Do not edit by hand: re-run suplementario.py and a_apendice.py.
%% Requires in the preamble of the main text:  \newtheorem{lemma}{Lemma}
%% ======================================================================
\appendix
\renewcommand{\thefigure}{\thesection.\arabic{figure}}
\renewcommand{\thetable}{\thesection.\arabic{table}}
\renewcommand{\theequation}{\thesection.\arabic{equation}}
\renewcommand{\theproposition}{\thesection.\arabic{proposition}}
\renewcommand{\thelemma}{\thesection.\arabic{lemma}}
\renewcommand{\theremark}{\thesection.\arabic{remark}}
"""

# section titles of the supplement -> appendix structure
ESTRUCTURA = [
    (r"\section{Mathematical results}" "\n" r"\label{sec:S-math}",
     r"\section{Mathematical results}" "\n" r"\label{app:math}" "\n" + RESET),
    (r"\section{Synthetic validation}" "\n" r"\label{sec:S-synth}",
     r"\section{Synthetic validation and diagnostic of the submitted analysis}" "\n"
     r"\label{app:synth}" "\n" + RESET + "\n\n" r"\subsection{Synthetic validation}"),
    (r"\section{Diagnostic of the submitted analysis}" "\n" r"\label{sec:S-submitted}",
     r"\subsection{Diagnostic of the submitted analysis}" "\n" r"\label{app:submitted}"),
    (r"\section{Community model: species, interfaces and medium}" "\n" r"\label{sec:S-model}",
     r"\section{Community model: medium and curation}" "\n" r"\label{app:model}" "\n" + RESET
     + "\n\n" r"\subsection{Medium and exchange space}"),
    (r"\section{Curation of the community model}" "\n" r"\label{sec:S-curation}",
     r"\subsection{Curation of the community model}" "\n" r"\label{app:curation}"),
    (r"\section{Schubert descriptors per species}" "\n" r"\label{sec:S-desc}",
     r"\section{Additional results}" "\n" r"\label{app:results}" "\n" + RESET
     + "\n\n" r"\subsection{Schubert descriptors per species}"),
    (r"\section{Robustness}" "\n" r"\label{sec:S-robust}",
     r"\subsection{Robustness}" "\n" r"\label{app:robust}"),
    (r"\section{Persistent homology}" "\n" r"\label{sec:S-ph}",
     r"\subsection{Persistent homology}" "\n" r"\label{app:ph}"),
    (r"\section{Cross-feeding in the community model}" "\n" r"\label{sec:S-eco}",
     r"\section{Cross-feeding in the community model}" "\n" r"\label{app:ecology}" "\n" + RESET),
    (r"\section{Software and reproducibility}" "\n" r"\label{sec:S-software}",
     r"\section{Software and reproducibility}" "\n" r"\label{app:software}" "\n" + RESET),
]

# references to the main text and to the supplement itself
REFS = [
    ("Proposition~1 of the main text", r"Proposition~\ref{prop:U}"),
    ("Well-definedness of Algorithm 1", r"Well-definedness of Algorithm~\ref{alg:schubert}"),
    ("returned by Algorithm 1", r"returned by Algorithm~\ref{alg:schubert}"),
    ("a literal implementation of Algorithm~1", r"a literal implementation of Algorithm~\ref{alg:schubert}"),
    ("the ``tiers reversed'' analysis of the main text",
     r"the ``tiers reversed'' analysis (Section~\ref{subsec:sens-flag})"),
    ("(main Table~7)", r"(Table~\ref{tab:variantes})"),
    ("Non-significant results in the main text",
     r"Non-significant results in Section~\ref{subsec:resultado-h1a}"),
    ("(main Section~6.3;", r"(Section~\ref{subsec:raw};"),
    ("The main text therefore reports", r"Section~\ref{subsec:estadistica} therefore reports"),
    ("mechanical dependence of Remark~1 (main text)", r"mechanical dependence of Remark~\ref{rem:dimension}"),
    ("listed in main Table~5", r"listed in Table~\ref{tab:interfaz-especies}"),
    ("discussed in main Section~7.5", r"discussed in Section~\ref{sec:limitations}"),
    ("(Section~\\ref{sec:S-curation})", r"(\ref{app:curation})"),
    ("figures, tables and this document", "figures, tables and these appendices"),
    ("(Appendix~\\ref{sec:S-eco})", r"(Appendix~\ref{app:ecology})"),
    ("(Section~\\ref{sec:S-eco})", r"(Appendix~\ref{app:ecology})"),
    ("Section~\\ref{sec:S-curation}", r"Appendix~\ref{app:curation}"),
    ("model curation (Section~\\ref{sec:S-curation})", r"model curation (Appendix~\ref{app:model})"),
]


def convertir(tex):
    i = tex.index(r"\section{Mathematical results}")
    j = tex.index(r"\begin{thebibliography}")
    cuerpo = tex[i:j].rstrip()
    for a, b in ESTRUCTURA:
        assert a in cuerpo, a
        cuerpo = cuerpo.replace(a, b)
    # curation subsections become subsubsections
    k0 = cuerpo.index(r"\label{app:curation}")
    k1 = cuerpo.index(r"\section{Additional results}")
    cur = cuerpo[k0:k1].replace(r"\subsection{", r"\subsubsection{")
    cuerpo = cuerpo[:k0] + cur + cuerpo[k1:]
    k0 = cuerpo.index(r"\label{app:robust}")
    k1 = cuerpo.index(r"\subsection{Persistent homology}")
    rob = cuerpo[k0:k1].replace(r"\subsection{", r"\subsubsection{")
    cuerpo = cuerpo[:k0] + rob + cuerpo[k1:]
    # the mathematical appendix keeps subsections
    for a, b in REFS:
        cuerpo = cuerpo.replace(a, b)
    # labels: S- -> A-
    cuerpo = re.sub(r"\{(fig|tab|eq|lem|prop):S-", r"{\1:A-", cuerpo)
    cuerpo = cuerpo.replace(r"\label{eq:matrix}", r"\label{eq:A-matrix}")
    cuerpo = cuerpo.replace(r"\ref{eq:matrix}", r"\ref{eq:A-matrix}")
    cuerpo = cuerpo.replace(r"{lem:delta}", r"{lem:A-delta}").replace(r"{lem:resol}", r"{lem:A-resol}")
    # cas-dc proofs and two-column floats
    cuerpo = cuerpo.replace(r"\begin{proof}", r"\begin{pf}").replace(r"\end{proof}", r"\end{pf}")
    cuerpo = cuerpo.replace(r"\begin{table}[H]", r"\begin{table*}[!t]").replace(r"\end{table}", r"\end{table*}")
    cuerpo = cuerpo.replace(r"\begin{figure}[H]", r"\begin{figure*}[!t]").replace(r"\end{figure}", r"\end{figure*}")
    cuerpo = cuerpo.replace(r"width=0.55\linewidth", r"width=0.5\textwidth")
    cuerpo = cuerpo.replace(r"width=\linewidth", r"width=\textwidth")
    cuerpo = cuerpo.replace(r"p{11cm}", r"p{0.75\textwidth}")
    # \remark in the supplement used amsthm's remark style; the main text defines remark
    leftovers = [m for m in ("main text", "main Table", "main Section", "Supplementary")
                 if m in cuerpo]
    if leftovers:
        print("WARNING: unconverted references:", leftovers)
    return CABECERA + "\n" + cuerpo + "\n"


if __name__ == "__main__":
    out = convertir(open(SRC, encoding="utf-8").read())
    open(DST, "w", encoding="utf-8").write(out)
    print("written", DST)
